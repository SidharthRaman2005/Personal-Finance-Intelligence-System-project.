export const INVESTMENT_NAME_SUGGESTIONS = {
  Stocks: STOCK_SUGGESTIONS,
  "Mutual Funds": MUTUAL_FUND_SUGGESTIONS,
};

export const isSuggestionType = (type) => type === "Stocks" || type === "Mutual Funds";

export const getInvestmentNameSuggestions = (type, query = "", limit = 12) => {
  const suggestions = INVESTMENT_NAME_SUGGESTIONS[type] || [];
  const normalizedQuery = query.trim().toLowerCase();

  if (!normalizedQuery) {
    return suggestions.slice(0, limit);
  }

  return suggestions
    .filter((name) => name.toLowerCase().includes(normalizedQuery))
    .slice(0, limit);
};
